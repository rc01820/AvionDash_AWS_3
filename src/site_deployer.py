"""Web-tier deployer — CloudFormation custom resource used by
cloudformation/avionpulse.yaml (the plain-CloudFormation path).

The code zip built by scripts/package.py carries the SPA under web/. On
Create/Update this function copies those files into the site bucket, writes
static/js/config.js from the stack parameters and invalidates CloudFront, so a
stack created from the AWS console serves the site with no CLI steps. On Delete
it empties the bucket so CloudFormation can remove it.

Properties: Bucket, DistributionId, AppEnv, AppVersion, DatadogSite,
            RumApplicationId, RumClientToken, CodeKey (changes trigger a redeploy)
"""
import logging
import mimetypes
import os
import time

import cfn
import telemetry
from store import err_code

telemetry.setup_logging()
log = logging.getLogger("avionpulse.site")

WEB_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "web")

CONTENT_TYPES = {".html": "text/html; charset=utf-8", ".js": "application/javascript; charset=utf-8",
                 ".css": "text/css; charset=utf-8", ".svg": "image/svg+xml", ".json": "application/json"}
NO_CACHE = {"index.html", "static/js/config.js"}

RUM_REGIONS = {"datadoghq.eu": "eu1", "us3.datadoghq.com": "us3", "us5.datadoghq.com": "us5",
               "ap1.datadoghq.com": "ap1", "ap2.datadoghq.com": "ap2"}


def _js(value):
    return str(value or "").replace("\\", "\\\\").replace("'", "\\'")


def config_js(props):
    site = props.get("DatadogSite") or "datadoghq.com"
    region = RUM_REGIONS.get(site, "us1")
    return (
        "// Generated by the SiteDeployment custom resource — do not edit by hand.\n"
        "window.AVIONPULSE_CONFIG = {\n"
        f"  env: '{_js(props.get('AppEnv', 'demo'))}',\n"
        f"  version: '{_js(props.get('AppVersion', '1.0.0'))}',\n"
        "  rum: {\n"
        f"    applicationId: '{_js(props.get('RumApplicationId'))}',\n"
        f"    clientToken: '{_js(props.get('RumClientToken'))}',\n"
        f"    site: '{_js(site)}',\n"
        f"    scriptUrl: 'https://www.datadoghq-browser-agent.com/{region}/v6/datadog-rum.js',\n"
        "    replaySampleRate: 20,\n"
        "  },\n"
        "};\n"
    )


def _files(web_root):
    for dirpath, _, names in os.walk(web_root):
        for name in names:
            full = os.path.join(dirpath, name)
            yield full, os.path.relpath(full, web_root).replace(os.sep, "/")


def _headers(key):
    ext = os.path.splitext(key)[1].lower()
    ctype = CONTENT_TYPES.get(ext) or mimetypes.guess_type(key)[0] or "application/octet-stream"
    cache = "no-cache" if key in NO_CACHE else "public, max-age=300"
    return {"ContentType": ctype, "CacheControl": cache}


def publish(props, s3, cloudfront, web_root=WEB_ROOT):
    bucket = props["Bucket"]
    count = 0
    for full, key in _files(web_root):
        if key == "static/js/config.js":
            continue
        with open(full, "rb") as fh:
            s3.put_object(Bucket=bucket, Key=key, Body=fh.read(), **_headers(key))
        count += 1
    s3.put_object(Bucket=bucket, Key="static/js/config.js", Body=config_js(props).encode(),
                  **_headers("static/js/config.js"))
    count += 1
    if props.get("DistributionId"):
        cloudfront.create_invalidation(
            DistributionId=props["DistributionId"],
            InvalidationBatch={"Paths": {"Quantity": 1, "Items": ["/*"]},
                               "CallerReference": f"avionpulse-{int(time.time())}"},
        )
    log.info("Published %d objects to s3://%s", count, bucket)
    return f"published {count} objects", {"Objects": str(count)}


def empty_bucket(props, s3):
    bucket = props["Bucket"]
    removed = 0
    paginator = s3.get_paginator("list_objects_v2")
    try:
        for page in paginator.paginate(Bucket=bucket):
            keys = [{"Key": o["Key"]} for o in page.get("Contents", [])]
            if keys:
                s3.delete_objects(Bucket=bucket, Delete={"Objects": keys, "Quiet": True})
                removed += len(keys)
    except Exception as e:  # bucket already gone (e.g. rollback of a failed create) is fine
        if err_code(e) != "NoSuchBucket":
            raise
    log.info("Removed %d objects from s3://%s", removed, bucket)
    return f"removed {removed} objects", {}


def handler(event, context):
    import boto3

    s3, cloudfront = boto3.client("s3"), boto3.client("cloudfront")
    if event.get("ResourceProperties", {}).get("Mode") == "cleanup":
        # Recorder bucket: nothing to publish, just empty it on stack delete.
        cfn.run(event, context,
                lambda props: ("nothing to publish", {}),
                lambda props: empty_bucket(props, s3),
                physical_id="avionpulse-recorder-cleanup")
        return
    cfn.run(event, context,
            lambda props: publish(props, s3, cloudfront),
            lambda props: empty_bucket(props, s3),
            physical_id="avionpulse-site")
